export type TranslationKey = keyof (typeof translations)["en"];

/** Simple {placeholder} substitution for the handful of keys that need it. */
export function formatTranslation(template: string, vars: Record<string, string>): string {
  return template.replace(/\{(\w+)\}/g, (match, key) => vars[key] ?? match);
}

/**
 * Plain, dependency-free lookup — safe in both Server and Client Components
 * (unlike `getTranslator` in `get-lang.ts`, which needs `next/headers`).
 * Client components receive `lang` as a prop from their server parent
 * (which read it via `getLang()`) rather than re-reading the cookie.
 */
export function translate(lang: Lang, key: TranslationKey, vars?: Record<string, string>): string {
  const template = translations[lang][key];
  return vars ? formatTranslation(template, vars) : template;
}
